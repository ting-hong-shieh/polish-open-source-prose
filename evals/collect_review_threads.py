#!/usr/bin/env python3
"""Collect pull request threads where reviewers comment on AI use, claims, or evidence.

Reads public data through the GitHub API (`gh`), writes one JSON file per pull request
under $POLISH_EVAL_DATA/Raw/polish-open-source-prose/github-threads/, and an index.csv
that marks threads where a reviewer commented and the author then edited the title or
description. Raw files contain other people's text and usernames: keep them local.

Usage: POLISH_EVAL_DATA=/mnt/d/Data python3 evals/collect_review_threads.py [--since 2025-10-01]
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import re
import subprocess
import time
from pathlib import Path

REPOS = ["apache/airflow", "apache/datafusion", "apache/arrow", "python/cpython"]
PHRASES = [
    "AI-generated", "LLM", "AI slop", "ChatGPT", "generated by AI", "AI tool",
    "provide evidence", "does not match", "your own words",
]
MAINTAINERS = {"MEMBER", "OWNER", "COLLABORATOR"}
SIGNAL = re.compile(r"\b(ai|llms?|chatgpt|copilot|claude|gemini)\b|ai-generated|generated by|slop|"
                    r"evidence|does(?:n't| not) match|own words|verbose|overclaim|misleading", re.I)

QUERY = """
query($owner:String!, $name:String!, $number:Int!) {
  repository(owner:$owner, name:$name) { pullRequest(number:$number) {
    number title body state merged createdAt closedAt url
    author { login } authorAssociation
    userContentEdits(first:30) { totalCount nodes { editedAt diff editor { login } } }
    timelineItems(first:30, itemTypes:[RENAMED_TITLE_EVENT]) {
      nodes { ... on RenamedTitleEvent { createdAt previousTitle currentTitle actor { login } } } }
    comments(first:100) { nodes { author { login } authorAssociation createdAt body } }
    reviews(first:50) { nodes { author { login } authorAssociation state submittedAt body
      comments(first:20) { nodes { author { login } authorAssociation createdAt body path } } } }
  } }
}"""


def gh(*args: str) -> str:
    for attempt in range(5):
        p = subprocess.run(["gh", *args], capture_output=True, text=True)
        if p.returncode == 0:
            return p.stdout
        if "rate limit" in p.stderr.lower() or "secondary" in p.stderr.lower():
            time.sleep(60 * (attempt + 1))
            continue
        raise RuntimeError(p.stderr.strip())
    raise RuntimeError("gh kept hitting rate limits")


def search(repo: str, phrase: str, since: str) -> list[int]:
    out = gh("search", "prs", "--repo", repo, f'"{phrase}" in:comments', f"updated:>={since}",
             "--limit", "50", "--json", "number", "-q", ".[].number")
    time.sleep(2.2)  # search API: 30 requests per minute
    return [int(x) for x in out.split()]


def fetch(repo: str, number: int) -> dict:
    owner, name = repo.split("/")
    out = gh("api", "graphql", "-f", f"query={QUERY}", "-F", f"owner={owner}",
             "-F", f"name={name}", "-F", f"number={number}")
    return json.loads(out)["data"]["repository"]["pullRequest"]


def all_comments(pr: dict) -> list[dict]:
    items = list(pr["comments"]["nodes"])
    for review in pr["reviews"]["nodes"]:
        items.append({**review, "createdAt": review.get("submittedAt")})
        items.extend(review["comments"]["nodes"])
    return [c for c in items if c.get("body")]


def summarize(repo: str, pr: dict) -> dict:
    author = (pr.get("author") or {}).get("login")
    def who(c: dict) -> str:
        return (c.get("author") or {}).get("login") or ""
    # authorAssociation is unreliable: members with private org membership show as
    # CONTRIBUTOR. Count every human reviewer and record association separately.
    flagged = [c for c in all_comments(pr)
               if who(c) != author and not who(c).endswith("[bot]") and "bot" not in who(c).lower()
               and SIGNAL.search(c["body"])]
    first = min((c["createdAt"] for c in flagged), default=None)
    body_edits_after = [e for e in pr["userContentEdits"]["nodes"]
                        if first and e["editedAt"] > first]
    renames_after = [r for r in pr["timelineItems"]["nodes"] if first and r and r["createdAt"] > first]
    author_replied = any((c.get("author") or {}).get("login") == author and first and c["createdAt"] > first
                         for c in all_comments(pr))
    return {
        "repo": repo, "number": pr["number"], "url": pr["url"], "state": pr["state"],
        "merged": pr["merged"], "reviewer_flag_comments": len(flagged),
        "flags_by_listed_maintainer": sum(c.get("authorAssociation") in MAINTAINERS for c in flagged),
        "first_flag_at": first, "body_edits_after_flag": len(body_edits_after),
        "title_renames_after_flag": len(renames_after), "author_replied_after_flag": author_replied,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", default="2025-10-01")
    opts = ap.parse_args()
    root = Path(os.environ.get("POLISH_EVAL_DATA", "/mnt/d/Data"))
    out = root / "Raw/polish-open-source-prose/github-threads"
    out.mkdir(parents=True, exist_ok=True)

    candidates: dict[tuple[str, int], set[str]] = {}
    for repo in REPOS:
        for phrase in PHRASES:
            for n in search(repo, phrase, opts.since):
                candidates.setdefault((repo, n), set()).add(phrase)
    print(f"{len(candidates)} candidate pull requests", flush=True)

    rows = []
    for (repo, n), phrases in sorted(candidates.items()):
        path = out / f"{repo.replace('/', '__')}__{n}.json"
        if path.exists():
            pr = json.loads(path.read_text())["pull_request"]
        else:
            pr = fetch(repo, n)
            path.write_text(json.dumps({"repo": repo, "matched_phrases": sorted(phrases),
                                        "fetched_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                        "pull_request": pr}, ensure_ascii=False, indent=1))
        rows.append({**summarize(repo, pr), "matched_phrases": "|".join(sorted(phrases))})

    with (out / "index.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                            cwd=Path(__file__).resolve().parent).stdout.strip()
    (out / "MANIFEST.json").write_text(json.dumps({
        "produced_by": "evals/collect_review_threads.py",
        "repository": "https://github.com/ting-hong-shieh/polish-open-source-prose",
        "commit": commit, "since": opts.since, "repos": REPOS, "phrases": PHRASES,
        "collected_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "pull_requests": len(rows), "publishable": "no: third-party text and usernames",
    }, indent=1) + "\n")
    useful = [r for r in rows if r["reviewer_flag_comments"] and
              (r["body_edits_after_flag"] or r["title_renames_after_flag"] or r["author_replied_after_flag"])]
    print(f"{len(rows)} fetched; {sum(1 for r in rows if r['reviewer_flag_comments'])} with a reviewer flag; "
          f"{len(useful)} where the author edited or replied afterwards")


if __name__ == "__main__":
    main()

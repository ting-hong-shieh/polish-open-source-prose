def stratified(rows: list[dict], n: int, rng: random.Random) -> list[dict]:
    """n rows drawn without replacement, allocated to repositories in proportion to their share
    of `rows` (largest remainder), uniform within each repository."""
    if n >= len(rows):
        return list(rows)
    by_repo: dict[str, list[dict]] = {}
    for r in sorted(rows, key=lambda r: (r["repo"], str(r["id"]))):
        by_repo.setdefault(r["repo"], []).append(r)
    quota = {repo: n * len(v) / len(rows) for repo, v in by_repo.items()}
    alloc = {repo: int(q) for repo, q in quota.items()}
    for repo in sorted(quota, key=lambda k: (-(quota[k] - alloc[k]), k))[:n - sum(alloc.values())]:
        alloc[repo] += 1
    return [r for repo in sorted(by_repo) for r in rng.sample(by_repo[repo], alloc[repo])]


def fence(body: str) -> str:
    run = max((len(m) for m in re.findall(r"`+|~+", body)), default=0)
    return "`" * max(3, run + 1)


def spot_check(n: int, seed: int, src: Path, out: Path, sheet: Path, fmt: str = "fenced") -> None:
    """Blind sheet of n random positives and n random negatives (stratified by repository), in
    shuffled order. The sheet shows the comment and its context but not the classifier's label
    or quoted sentence; the key file holds those. `fmt` "flags" writes the round-4 flag-sheet
    layout (build_case_files.py: PR and comment lines, the comment as a block quote, a yes/no
    flag line and a Note line); "fenced" the original layout with **Your answer:**."""
    items = {c["id"]: c for c in read_jsonl(src)}
    ans = [r for r in latest(read_jsonl(out)).values() if answered(r)]
    rng = random.Random(seed)
    pos = stratified([r for r in ans if r["answer"]["criticizes_text"]], n, rng)
    neg = stratified([r for r in ans if not r["answer"]["criticizes_text"]], n, rng)
    picks = pos + neg
    rng.shuffle(picks)
    sheet.parent.mkdir(parents=True, exist_ok=True)
    md = [f"# Classifier spot check: {len(picks)} comments", "",
          f"Drawn {time.strftime('%Y-%m-%d')} with seed {seed} from `{out.name}`: {len(pos)} that the classifier "
          f"marked yes and {len(neg)} marked no, in random order. The label is hidden; it is in "
          f"`{sheet.name}.key.json`. Third-party text: keep this file out of Git.", "",
          "Question for each comment: does it criticize the pull request's TITLE or DESCRIPTION text (what the "
          "author wrote about the change), as opposed to only the code, tests, or process? A reply by the PR "
          "author, bot output, and 'description'/'title' meaning something in the code count as no.", "",
          "Mark each item `yes` or `no` after **Your answer:**.", ""]
    key = []
    if fmt == "flags":
        md[-4:] = ["For each comment, tick one flag: does it criticize the pull request's TITLE or DESCRIPTION "
                   "text (what the author wrote about the change), not only the code, tests, or process? A reply "
                   "by the PR author, bot output, and 'description'/'title' meaning something in the code count "
                   "as no.", ""]
    for i, r in enumerate(picks, 1):
        c = items[r["id"]]
        key.append({"n": i, "id": r["id"], "url": c["url"], "repo": c["repo"], "kind": c["kind"],
                    "label": r["answer"]["criticizes_text"], "label_kind": r["answer"].get("kind"),
                    "quoted_sentence": r["answer"].get("quoted_sentence")})
        if fmt == "flags":
            pr_url = c["url"].split("#")[0] if c["kind"] != "review_summary" else c["url"]
            quoted = c["body"].strip().replace("\n", "\n> ")
            md += [f"## {i}. {c['repo']} #{c['pr']}", "", f"- PR: {pr_url}", f"- PR title: {c['title']}",
                   f"- Comment: {c['url']} ({c['kind'].replace('_', ' ')}, {c['author']} ({c['association']}), "
                   f"{c['created_at']})", "", f"> {quoted}", "",
                   "**Flag** (criticizes the description or title): [ ] yes  [ ] no", "", "Note: ", ""]
            continue
        f = fence(c["body"])
        md += [f"## {i}. {c['repo']} #{c['pr']} ({c['kind'].replace('_', ' ')})", "",
               f"- PR title: {c['title']}", f"- PR author: {c['pr_author']}",
               f"- Comment by: {c['author']} ({c['association']}), {c['created_at']}", f"- Link: {c['url']}", "",
               f + "text", c["body"], f, "", "**Your answer:** ", ""]
    Path(str(sheet) + ".md").write_text("\n".join(md))
    Path(str(sheet) + ".key.json").write_text(json.dumps(
        {"seed": seed, "n_per_label": n, "input": str(src), "results": str(out), "positives_in_pool": sum(
            r["answer"]["criticizes_text"] for r in ans), "negatives_in_pool": sum(
            not r["answer"]["criticizes_text"] for r in ans), "items": key}, ensure_ascii=False, indent=1))
    print(f"spot check: {len(pos)} positives + {len(neg)} negatives (seed {seed}) -> {sheet}.md "
          f"and {sheet}.key.json; positives by repo {dict(Counter(r['repo'] for r in pos))}; "
          f"negatives by repo {dict(Counter(r['repo'] for r in neg))}")


def kappa(pairs: list[tuple[bool, bool]]) -> float:
    n = len(pairs)
    po = sum(a == b for a, b in pairs) / n
    pa, pb = sum(a for a, _ in pairs) / n, sum(b for _, b in pairs) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return (po - pe) / (1 - pe) if pe < 1 else 1.0


def trial_stats(seed: int) -> None:
    sample = {json.loads(l)["id"]: json.loads(l) for l in (TRIAL / "sample.jsonl").read_text().split("\n") if l}
    res = {}
    for which in MODELS:
        p = TRIAL / f"results-{which}.jsonl"
        if p.exists():
            res[which] = {json.loads(l)["id"]: json.loads(l) for l in p.read_text().split("\n") if l}
    print(f"sample: {len(sample)}; by repo {dict(Counter(c['repo'] for c in sample.values()))}; "
          f"by kind {dict(Counter(c['kind'] for c in sample.values()))}")
    for which, rows in res.items():
        ans = [r for r in rows.values() if r["answer"] is not None and isinstance(r["answer"].get("criticizes_text"), bool)]
        pos = [r for r in ans if r["answer"]["criticizes_text"]]
        print(f"\n## {which} ({MODELS[which]})\ncalls {len(rows)}, parsed {len(ans)}, positives {len(pos)} "
              f"({len(pos) / len(ans):.1%} of parsed)")
        print("  by repo:", {repo: f"{sum(r['answer']['criticizes_text'] for r in ans if r['repo'] == repo)}/"
                             f"{sum(r['repo'] == repo for r in ans)}" for repo in sorted({r['repo'] for r in ans})})
        print("  by kind:", {k: f"{sum(r['answer']['criticizes_text'] for r in ans if r['kind'] == k)}/"
                             f"{sum(r['kind'] == k for r in ans)}" for k in sorted({r['kind'] for r in ans})})
        print("  kinds:", dict(Counter(r["answer"].get("kind") for r in pos)))
        print("  unparsed/errors:", [r["id"] for r in rows.values() if r not in ans],
              "rc!=0:", sum(r["usage"].get("returncode") != 0 for r in rows.values()))
        keys = [k for k in ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "cached_input_tokens",
                            "output_tokens", "reasoning_output_tokens", "cost_usd", "seconds") if any(k in r["usage"] for r in rows.values())]
        for k in keys:
            vals = [r["usage"].get(k) or 0 for r in rows.values()]
            print(f"  mean {k}: {sum(vals) / len(vals):.4g} (min {min(vals):.4g}, max {max(vals):.4g}, sum {sum(vals):.4g})")
        rng = random.Random(seed)
        picks = rng.sample(pos, min(10, len(pos)))
        print("  quoted_sentence verbatim check on 10 random positives:")
        for r in picks:
            q = (r["answer"].get("quoted_sentence") or "").strip()
            body = sample[r["id"]]["body"]
            verb = bool(q) and q in body
            loose = bool(q) and re.sub(r"\s+", " ", q).lower() in re.sub(r"\s+", " ", body).lower()
            print(f"    {r['url']}: verbatim={verb} whitespace/case-insensitive={loose} len={len(q)}")
    if len(res) == 2:
        a, b = res["haiku"], res["astra"]
        pairs = [(a[i]["answer"]["criticizes_text"], b[i]["answer"]["criticizes_text"]) for i in sample
                 if i in a and i in b and a[i]["answer"] and b[i]["answer"]
                 and isinstance(a[i]["answer"].get("criticizes_text"), bool) and isinstance(b[i]["answer"].get("criticizes_text"), bool)]
        both = sum(x and y for x, y in pairs)
        only_a = sum(x and not y for x, y in pairs)
        only_b = sum(y and not x for x, y in pairs)
        neither = len(pairs) - both - only_a - only_b
        print(f"\n## agreement (n={len(pairs)}): both yes {both}, haiku only {only_a}, astra only {only_b}, "
              f"both no {neither}; agreement {(both + neither) / len(pairs):.1%}; kappa {kappa(pairs):.3f}")
        print("  disagreements:")
        for i in sample:
            if i in a and i in b and a[i]["answer"] and b[i]["answer"] and a[i]["answer"].get("criticizes_text") != b[i]["answer"].get("criticizes_text"):
                print(f"    {sample[i]['url']} ({sample[i]['kind']}): haiku={a[i]['answer'].get('criticizes_text')}/"
                      f"{a[i]['answer'].get('kind')} astra={b[i]['answer'].get('criticizes_text')}/{b[i]['answer'].get('kind')}")


